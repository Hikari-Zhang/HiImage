"""
模型安装 / 环境准备工具

负责首次启动和下载完成后的一次性副作用操作：
  - 创建目录结构
  - 建立符号链接
  - 写入占位文件

与 model_checker.py（只读、无副作用）职责严格分离。
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

from core.paths import HF_HOME as _HF_HOME

_log = logging.getLogger("model_setup")


def _ensure_hub_model_index(repo_id: str, hub_dir: Path) -> None:
    """
    若模型已用标准 hub 格式下载，确保 snapshot 目录中存在 model_index.json 占位文件，
    使 iopaint scan_diffusers_models() 能识别该模型。

    对尚未下载（hub 缓存不存在）的模型是安全的 no-op。
    """
    try:
        from huggingface_hub import snapshot_download
        snapshot_path = snapshot_download(
            repo_id=repo_id,
            local_files_only=True,
            cache_dir=str(hub_dir),
        )
        if not snapshot_path:
            return
        model_index = Path(snapshot_path) / "model_index.json"
        if not model_index.exists():
            placeholder = {
                "_class_name": "StableDiffusionInpaintPipeline",
                "_diffusers_version": "0.27.2",
                "_note": "Auto-generated by HiImage for iopaint scan detection.",
            }
            model_index.write_text(json.dumps(placeholder, indent=2))
            _log.info(f"[iopaint_bridge] 在 hub snapshot 中创建占位 model_index.json: {repo_id}")
    except Exception:
        pass  # hub 缓存不存在或 snapshot_download 失败，跳过


def ensure_iopaint_hub_links(model_id: str | None = None) -> None:
    """
    为 IOPaint server 模式的模型在标准 HF hub 缓存目录中创建软链接，
    使 iopaint 的 scan_diffusers_models() 能扫描到已下载的模型。

    背景：
      - HiImage 的下载器将模型存于 <HF_HOME>/manual/<org>--<repo>/ （扁平结构）
      - iopaint 的 scan_diffusers_models() 扫描 <HF_HUB_CACHE>/models--<org>--<repo>/
        snapshots/*/model_index.json（标准 HF hub 缓存结构）
      - 两者路径不兼容，导致 iopaint 每次都认为模型不存在并触发下载
      - 解决方案：在 hub/ 下创建 snapshots/main -> manual/<repo> 的软链接

    :param model_id: 指定单个 registry ID（如 "wm_sdxl"）；
                    为 None 时处理所有 iopaint_mode: server 的模型。
    """
    manual_dir: Path = _HF_HOME / "manual"
    hub_dir: Path = _HF_HOME / "hub"

    # 延迟导入避免循环依赖
    from core.model_registry import MODELS, MODEL_BY_ID
    from core.constants import IOPaintMode

    # 收集需要处理的模型（去重 hf_model_id）
    if model_id is not None:
        cfg = MODEL_BY_ID.get(model_id)
        candidates = [cfg] if cfg else []
    else:
        candidates = MODELS

    seen_repos: set[str] = set()
    for cfg in candidates:
        if cfg.get("iopaint_mode") != IOPaintMode.SERVER:
            continue
        repo_id: str = cfg.get("hf_model_id", "")
        if not repo_id or repo_id in seen_repos:
            continue
        seen_repos.add(repo_id)

        # 无论安装方式如何，都为 hub 格式安装确保 model_index.json 存在
        _ensure_hub_model_index(repo_id, hub_dir)

        manual_path = manual_dir / repo_id.replace("/", "--")
        if not manual_path.exists() or not manual_path.is_dir():
            continue  # manual/ 目录不存在，跳过 symlink 创建

        # 若 manual_path 中没有 model_index.json（如 PowerPaint_v2 特殊结构），
        # 自动创建占位文件，让 iopaint scan_diffusers_models() 能识别该模型
        model_index_path = manual_path / "model_index.json"
        if not model_index_path.exists():
            try:
                placeholder = {
                    "_class_name": "StableDiffusionInpaintPipeline",
                    "_diffusers_version": "0.27.2",
                    "_note": "Auto-generated by HiImage for iopaint scan detection.",
                }
                model_index_path.write_text(json.dumps(placeholder, indent=2))
                _log.info(f"[iopaint_bridge] 创建占位 model_index.json: {repo_id}")
            except OSError as e:
                _log.warning(f"[iopaint_bridge] 创建 model_index.json 失败: {repo_id} — {e}")
                continue

        # 构建 hub 标准路径：hub/models--<org>--<repo>/snapshots/main
        hub_model_dir = hub_dir / ("models--" + repo_id.replace("/", "--"))
        snapshots_dir = hub_model_dir / "snapshots"
        snapshot_link = snapshots_dir / "main"

        if snapshot_link.exists() or snapshot_link.is_symlink():
            # 符号链接已存在；若 refs/main 缺失（旧版安装）则补建
            refs_main_file = hub_model_dir / "refs" / "main"
            if not refs_main_file.exists():
                try:
                    refs_dir = hub_model_dir / "refs"
                    refs_dir.mkdir(parents=True, exist_ok=True)
                    refs_main_file.write_text("main")
                    _log.info(f"[iopaint_bridge] 补建 refs/main: {repo_id}")
                except OSError as e:
                    _log.warning(f"[iopaint_bridge] 补建 refs/main 失败: {repo_id} — {e}")
            continue  # 符号链接已存在，无需重建

        try:
            snapshots_dir.mkdir(parents=True, exist_ok=True)
            snapshot_link.symlink_to(manual_path.resolve())
            _log.info(f"[iopaint_bridge] 创建 hub 软链接: {repo_id} → {manual_path}")
            # 创建 refs/main 文件（内容 "main"），使 snapshot_download(local_files_only=True)
            # 能通过 refs/main → commit_hash → snapshots/<hash>/ 找到本模型
            refs_dir = hub_model_dir / "refs"
            refs_dir.mkdir(parents=True, exist_ok=True)
            refs_main_file = refs_dir / "main"
            if not refs_main_file.exists():
                refs_main_file.write_text("main")
                _log.info(f"[iopaint_bridge] 创建 refs/main: {repo_id}")
        except OSError as e:
            _log.warning(f"[iopaint_bridge] 创建软链接失败: {repo_id} — {e}")
